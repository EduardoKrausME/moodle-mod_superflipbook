namespace mod_superflipbook\mcp;

use local_mcp\security\authenticated_identity;
use local_mcp\write\tool\activity_create_base;
use mod_superflipbook\local\mcp_pdf_service;
use stdClass;

/**
 * Create one activity containing a PDF generated by an MCP client.
 */
final class create_activity extends activity_create_base {
    /**
     * Return the Moodle activity module name.
     *
     * @return string
     */
    protected function module_name(): string {
        return "superflipbook";
    }

    /**
     * Declare the PDF-specific properties needed to create the activity.
     *
     * @return array
     */
    protected function extra_properties(): array {
        return [
            "filename" => ["type" => "string", "minLength" => 5, "maxLength" => 255,
                "description" => "Safe .pdf filename without directory components."],
            "file_base64" => ["type" => "string", "minLength" => 1,
                "description" => "Base64 PDF bytes or data:application/pdf;base64,...; maximum decoded size 40 MiB."],
        ];
    }

    /**
     * List mandatory PDF fields for the activity creation request.
     *
     * @return array
     */
    protected function extra_required(): array {
        return ["filename", "file_base64"];
    }

    /**
     * Return the translated tool title.
     *
     * @return string
     */
    public function get_title(): string {
        return get_string("mcpcreate_title", "mod_superflipbook");
    }

    /**
     * Return the translated tool description.
     *
     * @return string
     */
    public function get_description(): string {
        return get_string("mcpcreate_description", "mod_superflipbook");
    }

    /**
     * Never echo PDF contents into a confirmation preview.
     *
     * @param array $arguments
     * @param authenticated_identity $identity
     * @return array
     */
    public function preview(array $arguments, authenticated_identity $identity): array {
        $result = parent::preview($arguments, $identity);
        [, $bytes] = mcp_pdf_service::validate_pdf($arguments["filename"], $arguments["file_base64"]);
        $result["file_size_bytes"] = strlen($bytes);
        $result["file_sha256"] = hash("sha256", $bytes);
        unset($result["upload_bytes_estimate"]);
        return $result;
    }

    /**
     * Configure safe defaults and place the PDF into a Moodle filemanager draft.
     *
     * @param stdClass $info
     * @param array $arguments
     * @param authenticated_identity $identity
     * @return void
     */
    protected function configure(stdClass $info, array $arguments, authenticated_identity $identity): void {
        $info->pdf = mcp_pdf_service::create_draft_pdf(
            $arguments["filename"], $arguments["file_base64"], $identity->userid
        );
        $info->minpercentage = 100;
        $info->minseconds = 0;
        $info->requirelastpage = 0;
        $info->requiredpages = "";
        $info->requireack = 0;
        $info->ackstatement = "";
        $info->allowdownload = 0;
        $info->allowprint = 0;
        $info->watermark = 1;
        $info->recordip = 0;
        $info->grade = 100;
        $info->completionreading = 0;
    }
}
